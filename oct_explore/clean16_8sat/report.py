"""8-SAT: build results/CLEAN_SCALING_16LEVEL_8SAT.md + results/clean_scaling_16level_8sat.png from results/clean16/*.json (whatever exists)."""
import json, os, glob, numpy as np, common as CM
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
NS_ = CM.TEST_N; rng = np.random.default_rng(0); NB = 2000
def cost(p): return 1 / np.clip(np.asarray(p, float), 1e-12, 1)
def mb(c): return np.median(c), np.quantile(c, .9)
def load(pref):
    out = {}
    for s in range(3):
        f = f"{CM.RES}/{pref}_s{s}.json"
        if not os.path.exists(f): continue
        J = json.load(open(f)); T = J.get("test", {})
        if "val" not in T and "val_S" not in J: continue
        out[s] = {k: cost(v["p"]) for k, v in T.items() if "p" in v}
        if "val" not in T:   # gcost (gnnw): val n=12 (200) summary of the early-stopped checkpoint used for testing
            h = dict((it, v) for it, v in J["hist"])[J["best_it"]]; out[s]["valmb"] = (h["median_inv_p"], h["B90_inv_p"])
    return out
M = {"QAOA L4 (shots)": load("Q"), "Global cost L4 (shots)": load("G"), "Native-projected cost L4, QAOA-style 8 params (shots)": load("QC"), "Native-projected cost L4 + GNN clause weights (shots)": load("GC")}
W = {}
for n in NS_:
    f = f"{CM.RES}/W_n{n}.json"
    if os.path.exists(f): W[str(n)] = np.array(json.load(open(f))["lookups"])
def fit(ns, ys): s, i = np.polyfit(ns, np.log2(ys), 1); return 2 ** s, 2 ** i
def boot(costs):   # costs: dict n -> array; returns 95% CI of b for median and B90
    bs = {0: [], 1: []}; ns = [n for n in NS_ if str(n) in costs]
    for _ in range(NB):
        st = [mb(rng.choice(costs[str(n)], len(costs[str(n)]))) for n in ns]
        for q in (0, 1): bs[q].append(fit(ns, [x[q] for x in st])[0])
    return {q: np.percentile(bs[q], [2.5, 97.5]) for q in (0, 1)}
rows = {}; fits = {}; info = {}
for name, S in M.items():
    if not S: continue
    vm = lambda s: S[s]["valmb"] if "valmb" in S[s] else mb(S[s]["val"])
    win = min(S, key=lambda s: sum(np.log(vm(s))) / 2); info[name] = (win, {s: vm(s) for s in S})
    rows[name] = {}
    for n in NS_:
        k = str(n)
        if all(k in S[s] for s in S) and k in S[win]:
            v = [mb(S[s][k]) for s in S]; rows[name][n] = (mb(S[win][k]), [min(x[0] for x in v), max(x[0] for x in v)], [min(x[1] for x in v), max(x[1] for x in v)])
    if all(str(n) in S[win] for n in NS_):
        fw = {q: fit(NS_, [mb(S[win][str(n)])[q] for n in NS_]) for q in (0, 1)}
        seeds = [s for s in S if all(str(n) in S[s] for n in NS_)]
        fr = {q: [fit(NS_, [mb(S[s][str(n)])[q] for n in NS_])[0] for s in seeds] for q in (0, 1)}
        fits[name] = (fw, boot(S[win]), fr)
WT = {}
for n in NS_:
    f = f"{CM.RES}/W_n{n}.json"
    if os.path.exists(f): WT[str(n)] = np.array(json.load(open(f))["tries"])
EXTRA = [("WalkSATlm (lookups)", W)]
for p in (4, 14, 60):
    f = f"{CM.RES}/P{p}.json"
    if os.path.exists(f): EXTRA.append((f"ref: paper's published angles p={p}, no training (shots)", {k: cost(v["p"]) for k, v in json.load(open(f))["test"].items() if k != "val"}))
EXTRA.append(("ref: WalkSATlm in paper unit (tries of n flips)", WT))
for name, Wd in EXTRA:
    if not Wd: continue
    rows[name] = {n: (mb(Wd[str(n)]), None, None) for n in NS_ if str(n) in Wd}
    if len(Wd) == 4: fits[name] = ({q: fit(NS_, [mb(Wd[str(n)])[q] for n in NS_]) for q in (0, 1)}, boot(Wd), None)
L = ["# CLEAN controlled scaling table: 16-level cavity chain, **8-SAT** (fresh data)", "",
     f"_Auto-generated by `oct_explore/clean16_8sat/report.py`. Status: see bottom._", "",
     "**Setup.** 16-level cavities (4 bits each), chain of K=n/4 cavities (n=8→2, 12→3, 16→4, 20→5). L=4 for all quantum methods. "
     "Random 8-SAT in the PAPER's ensemble (PRX Quantum 5, 030348, Def. 1 / Table 1): m ~ Poisson(176.54 n), 8 literals drawn with replacement, satisfiable only, no unique-solution filter "
     "(clauses at n=8/12/16/20 ≈ 1412/2118/2825/3531). Cost phase normalised by nm=1/176.54. NEW bases: train 61e9, test 62e9, val 63e9 (never used before). "
     "Native ckpt_110 itself is NOT included (k=4 hard-coded, see notes); the two 'Native-projected' rows are the k=8 native baselines (same chain gate structure). Train n=8+12; validation n=12 (200 formulas, seed selection only); test n=8,12,16,20, 100 unseen formulas each. "
     "Cost = exact 1/p from the simulated state (p clipped at 1e-12); median and B90 over the 100 test formulas. Quantum = shots, WalkSATlm = lookups (fresh starts + flips). "
     "n=8 and n=12 are **training sizes** (marked †) but their test formulas are unseen.", "",
     "Cells: winner (best validation score S=(ln med+ln B90)/2 on val n=12) value, with [min–max over the 3 training seeds].", ""]
L += ["| method | " + " | ".join(f"n={n}{'†' if n in (8, 12) else ''} median" for n in NS_) + " |", "|---|" + "---|" * 4]
def cell(r, q):
    if r is None: return "—"
    w, rm, rb = r; v = f"**{w[q]:.3g}**"
    rr = rm if q == 0 else rb
    return v + (f" [{rr[0]:.3g}–{rr[1]:.3g}]" if rr else "")
for name, R_ in rows.items(): L.append(f"| {name} | " + " | ".join(cell(R_.get(n), 0) for n in NS_) + " |")
L += ["", "| method | " + " | ".join(f"n={n}{'†' if n in (8, 12) else ''} B90" for n in NS_) + " |", "|---|" + "---|" * 4]
for name, R_ in rows.items(): L.append(f"| {name} | " + " | ".join(cell(R_.get(n), 1) for n in NS_) + " |")
L += ["", "## Growth fit cost ≈ C·bⁿ over n=8,12,16,20 (least squares on log2 cost)", "",
      "| method | stat | b (winner) | 95% bootstrap CI on b (test formulas) | 3-seed range of b | α=log2 b | C |", "|---|---|---|---|---|---|---|"]
for name, (fw, ci, fr) in fits.items():
    for q, st in ((0, "median"), (1, "B90")):
        b, C = fw[q]; L.append(f"| {name} | {st} | **{b:.3f}** | [{ci[q][0]:.3f}, {ci[q][1]:.3f}] | {('%.3f–%.3f' % (min(fr[q]), max(fr[q]))) if fr else '—'} | {np.log2(b):.3f} | {C:.3g} |")
L += ["", "## Seed selection (validation n=12, 200 formulas)", ""]
for name, (win, v) in info.items():
    L.append(f"- {name}: winner seed {win}; val med/B90 " + ", ".join(f"s{s} {m:.2f}/{b:.2f}" for s, (m, b) in sorted(v.items())))
open(f"{CM.ROOT}/results/CLEAN_SCALING_16LEVEL_8SAT.md", "w").write("\n".join(L) + "\n\n" + open(f"{CM.HERE}/NOTES.md").read() + "\n\n" + open(f"{CM.HERE}/VERDICT.md").read())
fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
for name, R_ in rows.items():
    ns = sorted(R_)
    for q in (0, 1):
        y = [R_[n][0][q] for n in ns]; l = ax[q].semilogy(ns, y, "o-", label=name)[0]
        if R_[ns[0]][1] is not None:
            lo = [R_[n][1 + q][0] for n in ns]; hi = [R_[n][1 + q][1] for n in ns]; ax[q].fill_between(ns, lo, hi, color=l.get_color(), alpha=.2)
        if name in fits: b, C = fits[name][0][q]; xx = np.linspace(8, 20, 50); ax[q].semilogy(xx, C * b ** xx, "--", color=l.get_color(), lw=.8)
for q, t in ((0, "median"), (1, "B90")):
    ax[q].set_xlabel("n (bits); † n=8,12 training sizes"); ax[q].set_ylabel(f"{t} cost (shots / lookups)"); ax[q].set_xticks(NS_); ax[q].set_title(f"{t}: 8-SAT, 16-level chain, fresh test sets"); ax[q].grid(alpha=.3, which="both")
ax[0].legend(fontsize=7); fig.tight_layout(); fig.savefig(f"{CM.ROOT}/results/clean_scaling_16level_8sat.png", dpi=150)
print("\n".join(L))
